/**
 * Java code for a query built on the query page, for another application to run the same search.
 * Two flavours: the UnboundID LDAP SDK (what this project's backend uses; pages through large results)
 * and plain JNDI (no dependency). Connection details come from the environment, never from the code.
 */

export type Scope = 'base' | 'one' | 'sub';

export interface QuerySpec {
  baseDn: string;
  scope: Scope;
  filter: string;
  attributes: string[];
  sizeLimit: number;
  /** ldap:// or ldaps:// URL used when LDAP_URL is not set. */
  url: string;
}

/** The UnboundID LDAP SDK version the backend builds with. */
export const UNBOUNDID_VERSION = '7.0.6';

/** A Java string literal. */
export function javaString(s: string): string {
  return '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r')
    .replace(/\t/g, '\\t') + '"';
}

function attributeArgs(attributes: string[]): string {
  return attributes.map(javaString).join(', ');
}

const UNBOUNDID_SCOPE: Record<Scope, string> = { base: 'BASE', one: 'ONE', sub: 'SUB' };
const JNDI_SCOPE: Record<Scope, string> = { base: 'OBJECT_SCOPE', one: 'ONELEVEL_SCOPE', sub: 'SUBTREE_SCOPE' };

/** A class using the UnboundID LDAP SDK, with paging so results past the server's page limit are returned. */
export function unboundIdCode(q: QuerySpec): string {
  const attrs = q.attributes.length ? attributeArgs(q.attributes) : '';
  return `// Gradle: implementation 'com.unboundid:unboundid-ldapsdk:${UNBOUNDID_VERSION}'
// Maven:  <dependency><groupId>com.unboundid</groupId><artifactId>unboundid-ldapsdk</artifactId>
//           <version>${UNBOUNDID_VERSION}</version></dependency>
import java.util.ArrayList;
import java.util.List;

import com.unboundid.asn1.ASN1OctetString;
import com.unboundid.ldap.sdk.LDAPConnection;
import com.unboundid.ldap.sdk.LDAPConnectionPool;
import com.unboundid.ldap.sdk.LDAPException;
import com.unboundid.ldap.sdk.LDAPSearchException;
import com.unboundid.ldap.sdk.LDAPURL;
import com.unboundid.ldap.sdk.ResultCode;
import com.unboundid.ldap.sdk.SearchRequest;
import com.unboundid.ldap.sdk.SearchResult;
import com.unboundid.ldap.sdk.SearchResultEntry;
import com.unboundid.ldap.sdk.SearchScope;
import com.unboundid.ldap.sdk.SimpleBindRequest;
import com.unboundid.ldap.sdk.SingleServerSet;
import com.unboundid.ldap.sdk.controls.SimplePagedResultsControl;
import com.unboundid.util.ssl.SSLUtil;
import com.unboundid.util.ssl.TrustStoreTrustManager;

/** Generated by the InsureDirectory query builder. */
public final class LdapQuery {

    static final String BASE_DN = ${javaString(q.baseDn)};
    static final SearchScope SCOPE = SearchScope.${UNBOUNDID_SCOPE[q.scope]};
    static final String FILTER = ${javaString(q.filter)};
    /** Attributes to return; none listed means all user attributes. */
    static final String[] ATTRIBUTES = {${attrs}};
    static final int SIZE_LIMIT = ${q.sizeLimit};
    static final int PAGE_SIZE = 500;

    private LdapQuery() {
    }

    /**
     * Runs the search. The pages of one search must stay on one connection (OpenLDAP ties the
     * paging cookie to it), so a single connection is taken from the pool for the whole search.
     */
    public static List<SearchResultEntry> search(final LDAPConnectionPool pool) throws LDAPException {
        final List<SearchResultEntry> out = new ArrayList<>();
        final LDAPConnection connection = pool.getConnection();
        boolean healthy = true;
        try {
            ASN1OctetString cookie = null;
            do {
                final SearchRequest request = new SearchRequest(BASE_DN, SCOPE, FILTER, ATTRIBUTES);
                request.setSizeLimit(SIZE_LIMIT);
                request.addControl(new SimplePagedResultsControl(PAGE_SIZE, cookie));
                final SearchResult result;
                try {
                    result = connection.search(request);
                } catch (final LDAPSearchException e) {
                    if (e.getResultCode() != ResultCode.SIZE_LIMIT_EXCEEDED) {
                        throw e;
                    }
                    out.addAll(e.getSearchEntries()); // SIZE_LIMIT reached
                    break;
                }
                out.addAll(result.getSearchEntries());
                final SimplePagedResultsControl paging = SimplePagedResultsControl.get(result);
                cookie = paging == null ? null : paging.getCookie();
            } while (cookie != null && cookie.getValueLength() > 0 && out.size() < SIZE_LIMIT);
        } catch (final LDAPException e) {
            healthy = e.getResultCode().isConnectionUsable();
            throw e;
        } finally {
            if (healthy) {
                pool.releaseConnection(connection);
            } else {
                pool.releaseDefunctConnection(connection);
            }
        }
        return out.size() > SIZE_LIMIT ? out.subList(0, SIZE_LIMIT) : out;
    }

    /** A pool from LDAP_URL, LDAP_BIND_DN and LDAP_BIND_PASSWORD; ldaps:// uses the JVM's trust store. */
    public static LDAPConnectionPool connect() throws Exception {
        final LDAPURL url = new LDAPURL(System.getenv().getOrDefault("LDAP_URL", ${javaString(q.url)}));
        final SingleServerSet server = "ldaps".equalsIgnoreCase(url.getScheme())
                ? new SingleServerSet(url.getHost(), url.getPort(),
                        new SSLUtil(new TrustStoreTrustManager(System.getProperty("java.home")
                                + "/lib/security/cacerts")).createSSLSocketFactory())
                : new SingleServerSet(url.getHost(), url.getPort());
        return new LDAPConnectionPool(server,
                new SimpleBindRequest(System.getenv("LDAP_BIND_DN"), System.getenv("LDAP_BIND_PASSWORD")), 1, 4);
    }

    public static void main(final String[] args) throws Exception {
        try (LDAPConnectionPool pool = connect()) {
            for (final SearchResultEntry e : search(pool)) {
                System.out.println(e.toLDIFString());
            }
        }
    }
}
`;
}

/** A class using JNDI only (java.naming), for applications that cannot add a dependency. */
export function jndiCode(q: QuerySpec): string {
  const attrs = q.attributes.length ? `new String[] {${attributeArgs(q.attributes)}}` : 'null';
  return `// No dependency: JNDI is part of the JDK (module java.naming).
import java.util.ArrayList;
import java.util.Hashtable;
import java.util.List;

import javax.naming.Context;
import javax.naming.NamingEnumeration;
import javax.naming.NamingException;
import javax.naming.directory.SearchControls;
import javax.naming.directory.SearchResult;
import javax.naming.ldap.InitialLdapContext;
import javax.naming.ldap.LdapContext;

/** Generated by the InsureDirectory query builder. */
public final class LdapQuery {

    static final String BASE_DN = ${javaString(q.baseDn)};
    static final String FILTER = ${javaString(q.filter)};
    /** Attributes to return; null means all user attributes. */
    static final String[] ATTRIBUTES = ${attrs};
    static final long SIZE_LIMIT = ${q.sizeLimit};

    private LdapQuery() {
    }

    public static List<SearchResult> search(final LdapContext ctx) throws NamingException {
        final SearchControls controls = new SearchControls();
        controls.setSearchScope(SearchControls.${JNDI_SCOPE[q.scope]});
        controls.setCountLimit(SIZE_LIMIT);
        controls.setReturningAttributes(ATTRIBUTES);
        final List<SearchResult> out = new ArrayList<>();
        final NamingEnumeration<SearchResult> results = ctx.search(BASE_DN, FILTER, controls);
        try {
            while (results.hasMore()) {
                out.add(results.next());
            }
        } catch (final javax.naming.SizeLimitExceededException e) {
            // SIZE_LIMIT reached: out holds the first SIZE_LIMIT entries
        } finally {
            results.close();
        }
        return out;
    }

    /** A context from LDAP_URL, LDAP_BIND_DN and LDAP_BIND_PASSWORD. */
    public static LdapContext connect() throws NamingException {
        final Hashtable<String, Object> env = new Hashtable<>();
        env.put(Context.INITIAL_CONTEXT_FACTORY, "com.sun.jndi.ldap.LdapCtxFactory");
        env.put(Context.PROVIDER_URL, System.getenv().getOrDefault("LDAP_URL", ${javaString(q.url)}));
        env.put(Context.SECURITY_AUTHENTICATION, "simple");
        env.put(Context.SECURITY_PRINCIPAL, System.getenv("LDAP_BIND_DN"));
        env.put(Context.SECURITY_CREDENTIALS, System.getenv("LDAP_BIND_PASSWORD"));
        return new InitialLdapContext(env, null);
    }

    public static void main(final String[] args) throws NamingException {
        final LdapContext ctx = connect();
        try {
            for (final SearchResult r : search(ctx)) {
                System.out.println(r.getNameInNamespace() + " " + r.getAttributes());
            }
        } finally {
            ctx.close();
        }
    }
}
`;
}
